-- M9 · Builder portal: job requests from builders, and the contact card.
--
-- Builders submit two kinds of request: a new job (address, plan, trades,
-- colors) or an update request about one of their homes. The office reviews
-- them: a new-job request becomes a job; an update request gets an answer
-- the builder can read.

create type public.job_request_kind as enum ('new_job', 'update');
create type public.job_request_status as enum ('submitted', 'approved', 'declined', 'answered');

create table public.job_requests (
  id                      uuid primary key default gen_random_uuid(),
  request_number          bigint generated by default as identity unique,
  kind                    public.job_request_kind not null default 'new_job',
  builder_id              uuid not null references public.builders (id) on delete cascade,
  -- Update requests: the home asked about. New-job requests: the job created on approval.
  job_id                  uuid references public.jobs (id) on delete set null,
  submitted_by            uuid references public.profiles (id) on delete set null default auth.uid(),
  construction_manager_id uuid references public.construction_managers (id) on delete set null,
  house_number            text,
  street                  text,
  subdivision             text,
  area                    text,
  plan_name               text,
  plan_number             text,
  elevation               text,
  lot_swing               public.lot_swing,
  trades                  public.trade[] not null default '{}',
  brick_color             text,
  stone_color             text,
  mortar_color            text,
  stucco_colors           text,
  wanted_by               date,
  message                 text,
  status                  public.job_request_status not null default 'submitted',
  response                text,
  reviewed_by             uuid references public.profiles (id) on delete set null,
  reviewed_at             timestamptz,
  created_at              timestamptz not null default now(),
  updated_at              timestamptz not null default now(),
  constraint job_request_shape check (
    (kind = 'update' and job_id is not null)
    or (kind = 'new_job' and house_number is not null and street is not null)
  )
);
create index job_requests_builder_id_idx on public.job_requests (builder_id);
create index job_requests_job_id_idx on public.job_requests (job_id);
create index job_requests_submitted_by_idx on public.job_requests (submitted_by);
create index job_requests_construction_manager_id_idx on public.job_requests (construction_manager_id);
create index job_requests_reviewed_by_idx on public.job_requests (reviewed_by);
create index job_requests_open_idx on public.job_requests (created_at) where status = 'submitted';
alter table public.job_requests enable row level security;

create trigger job_requests_set_updated_at
  before update on public.job_requests
  for each row execute function private.set_updated_at();

-- The team reads every request; a builder reads only their own company's.
create policy "Read job requests"
  on public.job_requests for select to authenticated
  using ((select private.is_team()) or builder_id = (select private.current_builder_id()));

-- Builders submit for their own company only, as themselves, unreviewed.
-- An update request must be about a home they can see.
create policy "Builders submit job requests"
  on public.job_requests for insert to authenticated
  with check (
    builder_id = (select private.current_builder_id())
    and submitted_by = (select auth.uid())
    and status = 'submitted'
    and response is null and reviewed_by is null and reviewed_at is null
    and ((kind = 'new_job' and job_id is null)
         or (kind = 'update' and (select private.can_read_job(job_id))))
  );

-- The office (admins and supervisors) reviews them.
create policy "Office reviews job requests"
  on public.job_requests for update to authenticated
  using ((select private.current_app_role()) in ('admin', 'supervisor'))
  with check ((select private.current_app_role()) in ('admin', 'supervisor'));

-- Stamp who reviewed and when.
create function private.job_requests_stamp_review()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if new.status <> 'submitted' and old.status = 'submitted' then
    new.reviewed_by := coalesce((select auth.uid()), new.reviewed_by);
    new.reviewed_at := now();
  end if;
  return new;
end;
$$;

create trigger job_requests_stamp_review
  before update of status on public.job_requests
  for each row execute function private.job_requests_stamp_review();

-- "Your Leander 3T Team" in the portal: the supervisors on a builder's open
-- homes, with their phone numbers. Builders can't read staff profiles, so
-- this returns only these three fields. A builder always gets their own
-- company; the team may preview any builder.
create function public.portal_contacts(p_builder uuid default null)
returns table (full_name text, phone text, homes bigint)
language sql
stable
security definer
set search_path = ''
as $$
  select p.full_name, p.phone, count(distinct j.id) as homes
  from public.jobs j
  join public.job_assignments a on a.job_id = j.id and a.kind = 'supervisor'
  join public.profiles p on p.id = a.profile_id and p.active
  where j.status <> 'completed'
    and j.builder_id = coalesce(
      private.current_builder_id(),
      case when private.is_team() then p_builder end)
  group by p.id, p.full_name, p.phone
  order by homes desc, p.full_name;
$$;
revoke execute on function public.portal_contacts(uuid) from public, anon;
grant execute on function public.portal_contacts(uuid) to authenticated;
