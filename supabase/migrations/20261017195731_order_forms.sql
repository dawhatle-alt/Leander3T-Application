-- M6 · Order forms: the branded PDFs sent to suppliers, and the review queue.
--
-- Three layouts, as in the legacy Documint setup:
--   masonry  one form per job covering its unplaced sand, mortar, lintel,
--            arch lintel and rock orders
--   stucco   one form per stucco supply order
--   paint    one form per paint order
-- Generating a form files the PDF, marks its orders ordered (which stamps the
-- ordered date), and puts the form in the review team's queue. The review team
-- approves it; they still send it to suppliers themselves.

create type public.order_form_layout as enum ('masonry', 'stucco', 'paint');
create type public.order_form_status as enum ('pending_review', 'approved');

create table public.order_forms (
  id            uuid primary key default gen_random_uuid(),
  form_number   bigint generated by default as identity unique,
  job_id        uuid not null references public.jobs (id) on delete cascade,
  layout        public.order_form_layout not null,
  -- The orders on this form: [{"type": "lintel", "id": "<uuid>", "number": 73}, ...]
  orders        jsonb not null default '[]'::jsonb
                  check (jsonb_typeof(orders) = 'array'),
  -- Object path in the "order-forms" bucket; never a URL. Each regeneration
  -- writes a new file (…-v2.pdf), so earlier versions stay on record.
  storage_path  text not null unique,
  version       int not null default 1 check (version >= 1),
  status        public.order_form_status not null default 'pending_review',
  generated_by  uuid references public.profiles (id) on delete set null default auth.uid(),
  generated_at  timestamptz not null default now(),
  reviewed_by   uuid references public.profiles (id) on delete set null,
  reviewed_at   timestamptz,
  notified_at   timestamptz,          -- when the review team was emailed
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now()
);
create index order_forms_job_id_idx on public.order_forms (job_id);
create index order_forms_generated_by_idx on public.order_forms (generated_by);
create index order_forms_reviewed_by_idx on public.order_forms (reviewed_by);
create index order_forms_pending_idx on public.order_forms (generated_at)
  where status = 'pending_review';
alter table public.order_forms enable row level security;

create trigger order_forms_set_updated_at
  before update on public.order_forms
  for each row execute function private.set_updated_at();

-- The internal team reads forms on jobs they can see. Crew managers and
-- builders never see order forms.
create policy "Team reads order forms on jobs they can see"
  on public.order_forms for select to authenticated
  using ((select private.is_team()) and (select private.can_read_job(job_id)));

create policy "Job editors generate order forms"
  on public.order_forms for insert to authenticated
  with check ((select private.can_write_job(job_id)));

create policy "Job editors regenerate and review order forms"
  on public.order_forms for update to authenticated
  using ((select private.can_write_job(job_id)))
  with check ((select private.can_write_job(job_id)));

create policy "Admins remove order forms"
  on public.order_forms for delete to authenticated
  using ((select private.is_admin()));

-- Stamp who reviewed and when; reset both when a form goes back to review.
create function private.order_forms_stamp_review()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if new.status = 'approved' and old.status is distinct from 'approved' then
    new.reviewed_by := coalesce((select auth.uid()), new.reviewed_by);
    new.reviewed_at := now();
  elsif new.status = 'pending_review' then
    new.reviewed_by := null;
    new.reviewed_at := null;
  end if;
  return new;
end;
$$;

create trigger order_forms_stamp_review
  before update of status on public.order_forms
  for each row execute function private.order_forms_stamp_review();

-- ---------------------------------------------------------------------------
-- Storage: job editors file PDFs under "<job_id>/…" in the order-forms bucket.
-- Files are never overwritten (each version has its own name).
-- ---------------------------------------------------------------------------
create policy "Job editors file order forms"
  on storage.objects for insert to authenticated
  with check (bucket_id = 'order-forms'
              and (select private.can_write_job(private.object_job_id(name))));

-- ---------------------------------------------------------------------------
-- The review team: who gets the "new order form" email. Set by admins.
-- ---------------------------------------------------------------------------
alter table public.profiles
  add column reviews_order_forms boolean not null default false;

create or replace function private.guard_profile_columns()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  -- auth.uid() is null for the service role and SQL run by the owner.
  if (select auth.uid()) is not null
     and not private.is_admin()
     and (new.id                      is distinct from old.id
       or new.role                    is distinct from old.role
       or new.builder_id              is distinct from old.builder_id
       or new.construction_manager_id is distinct from old.construction_manager_id
       or new.email                   is distinct from old.email
       or new.active                  is distinct from old.active
       or new.airtable_id             is distinct from old.airtable_id
       or new.reviews_order_forms     is distinct from old.reviews_order_forms)
  then
    raise exception 'Only an administrator can change role, company, email or access.'
      using errcode = '42501';
  end if;
  return new;
end;
$$;
