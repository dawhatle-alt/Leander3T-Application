-- ---------------------------------------------------------------------------
-- Shared behavior for all seven order tables: RLS, policies, indexes,
-- updated_at, and the ordered-date stamp.
-- ---------------------------------------------------------------------------

-- Automation 1: when an order's "ordered" flips true, stamp the ordered date.
-- (Replaces the five "Update ... Ordered Date" automations and their twins.)
create function private.orders_stamp_ordered_date()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if new.ordered and new.ordered_date is null then
    new.ordered_date := private.today_central();
  end if;
  return new;
end;
$$;

do $$
declare
  t text;
begin
  foreach t in array array[
    'sand_orders', 'mortar_orders', 'lintel_orders', 'arch_lintel_orders',
    'rock_orders', 'stucco_material_orders', 'paint_orders'
  ] loop
    execute format('alter table public.%I enable row level security', t);

    execute format('create index %I on public.%I (job_id)', t || '_job_id_idx', t);
    execute format('create index %I on public.%I (supplier_id)', t || '_supplier_id_idx', t);
    execute format('create index %I on public.%I (created_by)', t || '_created_by_idx', t);
    execute format('create index %I on public.%I (ordered) where not ordered', t || '_pending_idx', t);

    execute format($p$
      create policy "Staff who can see the job read its orders"
        on public.%I for select to authenticated
        using ((select private.is_staff()) and (select private.can_read_job(job_id)))
    $p$, t);

    execute format($p$
      create policy "Job editors and the job's crew managers create orders"
        on public.%I for insert to authenticated
        with check ((select private.can_order_for_job(job_id)))
    $p$, t);

    execute format($p$
      create policy "Job editors and the job's crew managers edit orders"
        on public.%I for update to authenticated
        using ((select private.can_order_for_job(job_id)))
        with check ((select private.can_order_for_job(job_id)))
    $p$, t);

    execute format($p$
      create policy "Admins delete orders; job editors delete unplaced orders"
        on public.%I for delete to authenticated
        using ((select private.is_admin())
               or (not ordered and (select private.can_write_job(job_id))))
    $p$, t);

    execute format(
      'create trigger %I before update on public.%I for each row execute function private.set_updated_at()',
      t || '_set_updated_at', t);

    execute format(
      'create trigger %I before insert or update of ordered on public.%I for each row execute function private.orders_stamp_ordered_date()',
      t || '_stamp_ordered_date', t);
  end loop;
end;
$$;

