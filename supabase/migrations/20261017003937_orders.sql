-- M1 · Material orders: seven order types, kept as seven tables (as in Airtable).
-- Shared columns on each: job, supplier, order number, ordered, ordered date,
-- requested delivery date, notes, created by.

-- Sand (yards)
create table public.sand_orders (
  id                      uuid primary key default gen_random_uuid(),
  order_number            bigint generated by default as identity unique,
  job_id                  uuid not null references public.jobs (id) on delete cascade,
  supplier_id             uuid references public.suppliers (id) on delete set null,
  sand_type               text,                 -- legacy: "Masonry"
  yards                   numeric(8, 2),
  bags                    numeric(8, 2),
  delivery_completed_date date,
  ordered                 boolean not null default false,
  ordered_date            date,
  requested_delivery_date date,
  notes                   text,
  created_by              uuid references public.profiles (id) on delete set null default auth.uid(),
  created_by_email        text,                 -- legacy Airtable creator, kept for history
  airtable_id             text unique,
  created_at              timestamptz not null default now(),
  updated_at              timestamptz not null default now()
);

