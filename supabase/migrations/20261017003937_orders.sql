create table public.stucco_order_items (
  order_id   uuid not null references public.stucco_material_orders (id) on delete cascade,
  item_code  text not null references public.stucco_items (code),
  quantity   numeric(8, 2) not null check (quantity >= 0),
  unit       text not null,           -- usually the item's default unit; legacy rows sometimes say "pieces" instead of "cases"
  note       text,                    -- legacy free text that could not be read as a number
  primary key (order_id, item_code)
);
create index stucco_order_items_item_code_idx on public.stucco_order_items (item_code);
alter table public.stucco_order_items enable row level security;

create function private.stucco_order_job_id(p_order_id uuid)
returns uuid
language sql
stable
security definer
set search_path = ''
as $$
  select o.job_id from public.stucco_material_orders o where o.id = p_order_id;
$$;
grant execute on function private.stucco_order_job_id(uuid) to authenticated;

create policy "Staff who can see the job read stucco line items"
  on public.stucco_order_items for select to authenticated
  using ((select private.is_staff())
         and (select private.can_read_job(private.stucco_order_job_id(order_id))));

create policy "Job editors and the job's crew managers manage stucco line items"
  on public.stucco_order_items for all to authenticated
  using ((select private.can_order_for_job(private.stucco_order_job_id(order_id))))
  with check ((select private.can_order_for_job(private.stucco_order_job_id(order_id))));
