import "server-only";
import type { SupabaseClient } from "@supabase/supabase-js";
import type { Database } from "@/lib/supabase/types";

// "New order form" email to the review team, through Resend's HTTP API.
// Until RESEND_API_KEY and ORDER_FORMS_FROM are set (needs a verified
// sending domain), this does nothing and the queue still works.

export function emailConfigured() {
  return Boolean(process.env.RESEND_API_KEY && process.env.ORDER_FORMS_FROM);
}

const esc = (s: string) =>
  s.replace(
    /[&<>"']/g,
    (c) =>
      ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" })[
        c
      ]!,
  );

export async function notifyReviewTeam(
  supabase: SupabaseClient<Database>,
  form: {
    title: string; // "Masonry order form"
    address: string;
    orders: string; // "#35, #27, #49"
    generatedBy: string;
    regenerated: boolean;
    reviewUrl: string;
    fileName: string;
    pdf: Uint8Array;
  },
): Promise<"sent" | "skipped" | "failed"> {
  if (!emailConfigured()) return "skipped";

  const { data: reviewers } = await supabase
    .from("profiles")
    .select("email")
    .eq("reviews_order_forms", true)
    .eq("active", true);
  const to = (reviewers ?? [])
    .map((r) => r.email)
    .filter((e): e is string => Boolean(e));
  if (!to.length) return "skipped";

  const verb = form.regenerated ? "updated" : "ready for review";
  const subject = `${form.title} ${verb} — ${form.address}`;
  const html = `<div style="font-family:Arial,sans-serif;font-size:15px;color:#241E19;line-height:1.5">
<p><strong>${esc(form.title)}</strong> for <strong>${esc(form.address)}</strong> is ${verb}.</p>
<p>Orders ${esc(form.orders)} · generated by ${esc(form.generatedBy)}.</p>
<p>The PDF is attached. Review and approve it in the app:</p>
<p><a href="${esc(form.reviewUrl)}" style="display:inline-block;background:#E4590F;color:#fff;padding:10px 18px;border-radius:6px;text-decoration:none;font-weight:bold">Open Order Forms</a></p>
<p style="color:#75685C;font-size:13px">Leander 3T · 127 Woodland Trail, Leander TX 78641</p>
</div>`;

  try {
    const res = await fetch("https://api.resend.com/emails", {
      method: "POST",
      headers: {
        Authorization: `Bearer ${process.env.RESEND_API_KEY}`,
        "Content-Type": "application/json",
      },
      body: JSON.stringify({
        from: process.env.ORDER_FORMS_FROM,
        to,
        subject,
        html,
        attachments: [
          {
            filename: form.fileName,
            content: Buffer.from(form.pdf).toString("base64"),
          },
        ],
      }),
    });
    return res.ok ? "sent" : "failed";
  } catch {
    return "failed";
  }
}
